import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {mkdtempSync,mkdirSync,writeFileSync,readFileSync,rmSync,existsSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {applyCommand} from './design-session.mjs';
import {createSafeCandidate} from './design-worktrees.mjs';
import {adoptCandidate,undoAdoption} from './design-adopt.mjs';
import {prepareSync} from './design-project-sync.mjs';

const root=mkdtempSync(join(tmpdir(),'atp-design-integration-'));
const site=join(root,'knowledge-site'), candidateDir=join(root,'editorial-option');
const git=(cwd,...args)=>execFileSync('git',['-C',cwd,...args],{encoding:'utf8'}).trim();
try{
 mkdirSync(site);
 git(site,'init','-b','main');
 git(site,'config','user.email','atp-test@example.invalid');
 git(site,'config','user.name','ATP test');
 mkdirSync(join(site,'src'));
 const project='# PROJECT.md｜我的個人網站專案脈絡\n\n## 6. 已確認的長期決策\n\n| ID | 日期 | 決策 | 理由／效果 | 狀態 | 來源（學員確認摘要） | 取代 ID |\n| --- | --- | --- | --- | --- | --- | --- |\n\n## 7. 目前階段與下一步\n- 開發中\n';
 writeFileSync(join(site,'PROJECT.md'),project);
 writeFileSync(join(site,'src','home.astro'),'<h1>Original heading</h1>\n');
 writeFileSync(join(site,'src','about.astro'),'<h1>Keep this page</h1>\n');
 git(site,'add','.');git(site,'commit','-m','student baseline');
 git(site,'checkout','-b','feat/student-design');
 applyCommand(site,'init',{site:'知識網站',scope:'首頁設計'});
 applyCommand(site,'add',{id:'editorial',title:'編輯首頁',first:'文章首屏',flow:'文章列表',mobile:'單欄',tradeoff:'圖片較少'});
 applyCommand(site,'choose',{id:'editorial',reason:'學員選擇文字優先'});
 applyCommand(site,'note',{type:'confirmed',text:'長中文標題不可截斷'});
 applyCommand(site,'note',{type:'rejected',text:'拒絕巨型照片 Hero'});
 applyCommand(site,'preserve',{text:'關於我頁面與文章 URL'});
 const created=createSafeCandidate({root:site,slug:'editorial',destination:candidateDir});
 assert.equal(created.branch,'design/editorial');
 writeFileSync(join(candidateDir,'src','home.astro'),'<h1>Article-first heading</h1>\n');
 writeFileSync(join(candidateDir,'src','about.astro'),'<h1>Unselected candidate change</h1>\n');
 git(candidateDir,'add','.');git(candidateDir,'commit','-m','design a distinct homepage');
 const original=readFileSync(join(site,'src','home.astro'),'utf8');
 assert.throws(()=>adoptCandidate({root:site,id:'editorial',paths:['src/home.astro'],approval:''}),/approved scope/);
 const planned=adoptCandidate({root:site,id:'editorial',paths:['src/home.astro'],approval:'首頁用文章',dryRun:true});
 assert.equal(planned.status,'READY_TO_REVIEW');
 assert.equal(readFileSync(join(site,'src','home.astro'),'utf8'),original);
 assert.deepEqual(planned.omitted,['src/about.astro']);
 assert.throws(()=>adoptCandidate({root:site,id:'editorial',paths:['PROJECT.md'],approval:'yes'}),/Unsafe or protected/);
 const result=adoptCandidate({root:site,id:'editorial',paths:['src/home.astro'],approval:'學員選用首頁',dryRun:false});
 assert.equal(result.status,'APPLIED_UNCOMMITTED');
 assert.match(readFileSync(join(site,'src','home.astro'),'utf8'),/Article-first/);
 assert.match(readFileSync(join(site,'src','about.astro'),'utf8'),/Keep this page/);
 const restored=undoAdoption({root:site,id:'editorial'});
 assert.equal(restored.status,'REVERTED_UNCOMMITTED');
 assert.equal(readFileSync(join(site,'src','home.astro'),'utf8'),original);
 const version=git(site,'rev-parse','HEAD');
 assert.equal(version,created.base,"neither adoption nor undo commits the student's site");
 const preview=prepareSync({root:site,approval:'學員已確認文字先行'});
 assert.equal(preview.changed,false);
 assert.equal(readFileSync(join(site,'PROJECT.md'),'utf8'),project);
 const sync=prepareSync({root:site,approval:'學員已確認文字先行',apply:true});
 assert.equal(sync.changed,true);
 const updated=readFileSync(join(site,'PROJECT.md'),'utf8');
 assert.ok(updated.includes('長中文標題不可截斷'));
 assert.ok(updated.includes('拒絕巨型照片 Hero'));
 assert.ok(updated.includes('關於我頁面'));
 assert.throws(()=>prepareSync({root:site,approval:'retry',apply:true}),/uncommitted edits/);
 git(site,'add','PROJECT.md');git(site,'commit','-m','student confirmed design decisions');
 applyCommand(site,'note',{type:'confirmed',text:'手機版列表維持單欄'});
 const later=prepareSync({root:site,approval:'學員下一次明確確認',apply:true});
 assert.equal(later.changed,true);
 const persisted=readFileSync(join(site,'PROJECT.md'),'utf8');
 assert.ok(persisted.includes('長中文標題不可截斷')&&persisted.includes('手機版列表維持單欄'));
 assert.equal((persisted.match(/長中文標題不可截斷/g)||[]).length,1,'repeatable sync must not duplicate old decisions');
 console.log('PASS: student worktree candidate, selective adoption, rollback and explicit PROJECT decisions');
 console.log('NOT TESTED: real learner website redesign or visual quality');
}finally{rmSync(root,{recursive:true,force:true});}
